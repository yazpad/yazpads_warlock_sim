// Append missing real gear IDs using the live export's raw item stats.
// Does not replace existing items, apply buffs or copy resolved player stats.
import fs from 'node:fs';
import path from 'node:path';
const snapshot = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const sourceCatalog = JSON.parse(fs.readFileSync(path.resolve(process.argv[3] || '../forever', 'assets/database/db.json'), 'utf8'));
const file = path.resolve(import.meta.dirname, '../threejs_webgl_des/data/items.json');
const original = fs.readFileSync(file, 'utf8');
const database = JSON.parse(original);
const slots = ['HEAD','NECK','SHOULDERS','BACK','CHEST','WRISTS','HANDS','WAIST','LEGS','FEET','RING1','RING2','TRINKET1','TRINKET2','MAIN_HAND','OFF_HAND','RANGED'];
const additions = [];
for (const [index, item] of snapshot.gearItems.entries()) {
  if (!item) continue;
  const existing = database.items.find(existing => existing.id === item.id);
  const metadata = sourceCatalog.items.find(source => source.id === item.id);
  if (!metadata) throw new Error(`Source UI metadata missing for ${item.id}`);
  const display = { quality:['POOR','COMMON','UNCOMMON','RARE','EPIC','LEGENDARY','ARTIFACT'][metadata.quality], phase:metadata.phase, icon:metadata.icon + '.png' };
  if (existing) {
    if (existing.source?.startsWith('wowsims/forever')) Object.assign(existing, display);
    continue;
  }
  const s = item.stats;
  if (s.HasteRating) throw new Error(`Item ${item.id} has haste; the app cannot represent it.`);
  if (snapshot.request.raid.parties[0].players[0].equipment.items[index].randomSuffix) throw new Error('Random suffix item stats need explicit resolution.');
  const slot = slots[index].replace('RING2','RING1').replace('TRINKET2','TRINKET1');
  const fields = { stamina:'Stamina', intellect:'Intellect', spirit:'Spirit', spell_power:'SpellDamage', shadow_power:'ShadowDamage', fire_power:'FireDamage', mp5:'MP5', spell_penetration:'SpellPiercing' };
  additions.push({ id:item.id, name:item.name, slot, ...display,
    ...Object.fromEntries(Object.entries(fields).map(([key, stat]) => [key, s[stat]])),
    spell_hit:s.SpellHitPercent + s.HitRating / snapshot.ratingConversions.hitRatingPerPercent,
    spell_crit:s.SpellCritPercent + s.CritRating / snapshot.ratingConversions.critRatingPerPercent,
    spell_haste:0, set_name:item.setName,
    source:'wowsims/forever live item export; see canonical fixture provenance' });
}
// Metadata refresh affects only entries previously generated by this script.
let refreshed = original;
for (const item of database.items.filter(item => item.source?.startsWith('wowsims/forever'))) {
  const previous = JSON.parse(original).items.find(previous => previous.id === item.id);
  refreshed = refreshed.replace(JSON.stringify(previous), JSON.stringify(item));
}
if (additions.length) {
  // Preserve the existing catalog's formatting and append only new entries.
  const end = refreshed.lastIndexOf(']');
  if (end < 0) throw new Error('Invalid item catalog');
  const updated = refreshed.slice(0, end).trimEnd() + ',\n' + additions.map(item => '    ' + JSON.stringify(item)).join(',\n') + '\n  ' + refreshed.slice(end);
  JSON.parse(updated);
  fs.writeFileSync(file, updated);
} else if (refreshed !== original) fs.writeFileSync(file, refreshed);
console.log(`Added ${additions.length} source-backed equipment items.`);
